/** Administration text in the current language. */
export function ta(key: AdminKey): string {
  return (getLocale() === 'he' ? he : en)[key];
}

/** Administration text with {placeholders}. */
export function taf(key: AdminKey, vars: Record<string, string | number>): string {
  return ta(key).replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

