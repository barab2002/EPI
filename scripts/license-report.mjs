#!/usr/bin/env node
// Third-party license inventory for production dependencies (EPI-012).
//   node scripts/license-report.mjs [--out FILE]
// Reads `pnpm licenses list --prod --json` (offline: uses node_modules). Fails when a license is
// not on the reviewed allowlist (copyleft, unknown or custom terms need an explicit decision).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

/** Permissive licenses reviewed as compatible with Apache-2.0 distribution (ADR-013). */
const ALLOWED = new Set([
  'MIT',
  'ISC',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'BlueOak-1.0.0',
  'Python-2.0', // argparse (JS port); PSF-style permissive
  '(MIT AND BSD-3-Clause)',
  'CC0-1.0',
  'Unlicense',
]);

const raw = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
const byLicense = JSON.parse(raw);
const rows = [];
for (const [license, pkgs] of Object.entries(byLicense)) {
  for (const p of pkgs) {
    for (const v of p.versions)
      rows.push({ name: p.name, version: v, license, homepage: p.homepage ?? '' });
  }
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const denied = rows.filter((r) => !ALLOWED.has(r.license));

const counts = Object.entries(byLicense)
  .map(([l, p]) => `${l}: ${p.length}`)
  .join(', ');
const outIdx = process.argv.indexOf('--out');
if (outIdx > 0) {
  const lines = [
    '# Third-party licenses (production dependencies)',
    '',
    `Generated by scripts/license-report.mjs. ${rows.length} packages — ${counts}.`,
    'EPI itself is Apache-2.0 (see LICENSE, NOTICE). Container base images carry their own licenses',
    '(node, postgres, keycloak — see their upstream projects).',
    '',
    '| Package | Version | License | Homepage |',
    '|---|---|---|---|',
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.homepage} |`),
    '',
  ];
  writeFileSync(process.argv[outIdx + 1], lines.join('\n'));
}
if (denied.length) {
  console.error('license-report: FAIL — licenses not on the allowlist:');
  for (const r of denied) console.error(`  ${r.name}@${r.version}: ${r.license}`);
  process.exit(1);
}
console.log(`license-report: PASS — ${rows.length} production packages (${counts})`);
